from __future__ import annotations

from typing import Any

from .patch_proposal import PatchProposal
from .shadow_workspace import ShadowValidationResult


class DraftPrError(ValueError):
    """Raised when a safe Draft PR body cannot be rendered."""


def render_draft_pr_body(
    *,
    report: dict[str, Any],
    proposal: PatchProposal,
    validation: ShadowValidationResult | None = None,
) -> str:
    """Render local Markdown only; this function never calls GitHub."""

    _validate_report(report)
    if not isinstance(proposal, PatchProposal) or not proposal.verify_integrity():
        raise DraftPrError("proposal failed integrity validation")
    if report["repo_snapshot_before"] != proposal.base_snapshot_hash:
        raise DraftPrError("analysis report and proposal snapshots do not match")
    if validation is not None:
        if not validation.verify_integrity():
            raise DraftPrError("validation receipt failed integrity validation")
        if validation.proposal_hash != proposal.proposal_hash:
            raise DraftPrError("validation receipt belongs to another proposal")
        if validation.base_snapshot_hash != proposal.base_snapshot_hash:
            raise DraftPrError("validation receipt belongs to another base snapshot")

    issue = report["issue"]
    plan = report["plan"]
    evidence = report["evidence"]
    if validation is None:
        validation_status = "未执行 / Not run"
    elif validation.verdict == "failed":
        validation_status = "失败 / Failed"
    elif validation.runner == "unsafe-local":
        validation_status = (
            "可信夹具本地通过（非隔离） / "
            "Trusted-fixture local pass (not isolated)"
        )
    else:
        validation_status = "Docker 隔离通过 / Docker-isolated pass"
    lines = [
        "## 背景 / Context",
        "",
        f"**{issue['title']}**",
        "",
        report["diagnosis"],
        "",
        "## 修改内容 / Changes",
        "",
    ]
    for index, step in enumerate(plan, start=1):
        evidence_ids = ", ".join(f"`{item}`" for item in step["evidence_ids"])
        lines.append(
            f"{index}. {step['action']} — {step['rationale']} "
            f"证据 / Evidence: {evidence_ids}"
        )
    lines.extend(["", "修改路径 / Changed paths:", ""])
    lines.extend(f"- `{path}`" for path in proposal.changed_paths)
    lines.extend(["", "## 证据 / Evidence", ""])
    for item in evidence[:12]:
        lines.append(
            f"- `{item['evidence_id']}` → `{item['path']}:{item['start_line']}-"
            f"{item['end_line']}` — {item['reason']}"
        )
    lines.extend(
        [
            "",
            "## 验证 / Validation",
            "",
            f"- Shadow Validation: **{validation_status}**",
        ]
    )
    if validation is not None:
        lines.extend(
            [
                f"- Runner: `{validation.runner}`",
                f"- Receipt: `{validation.receipt_hash}`",
                f"- Real repository unchanged: "
                f"`{str(validation.repository_unchanged).lower()}`",
            ]
        )
        for command in validation.commands:
            result = "通过 / Passed" if command.expectation_met else "失败 / Failed"
            lines.append(
                f"- `{command.name}`: {result} (exit `{command.exit_code}`)"
            )
        if validation.runner == "unsafe-local":
            lines.append(
                "- 警告：该回执在宿主机执行，只适用于可信夹具。 / "
                "Warning: this receipt used host execution and is valid only for "
                "trusted fixtures."
            )
    else:
        lines.append(
            "- 合并前必须完成隔离验证。 / Shadow validation is required before merge."
        )
    lines.extend(["", "建议测试 / Proposed tests:", ""])
    lines.extend(f"- {item}" for item in report["proposed_tests"])
    lines.extend(["", "## 风险 / Risks", ""])
    lines.extend(f"- {item}" for item in report["risks"])
    lines.extend(
        [
            "",
            "## 人工检查清单 / Human Review Checklist",
            "",
            "- [ ] 已逐行审查 Diff。 / The diff has been reviewed line by line.",
            "- [ ] 修改路径与证据范围一致。 / Changed paths match the evidence scope.",
            "- [ ] Docker 隔离验证回执可信且结果通过。 / The Docker-isolated validation receipt is trusted and passed.",
            "- [ ] 未向真实仓库自动写入。 / No automatic write was made to the real repository.",
            "",
            "## AI 辅助披露 / AI Assistance Disclosure",
            "",
            "本 Draft PR 文本由 IssueLens 根据可追溯代码证据生成，必须经过人工编辑和批准后才能发布。",
            "",
            "This Draft PR text was generated by IssueLens from traceable code evidence "
            "and must be edited and approved by a human before publication.",
            "",
            f"Proposal Hash: `{proposal.proposal_hash}`",
            f"Base Snapshot: `{proposal.base_snapshot_hash}`",
            "",
        ]
    )
    return "\n".join(lines)


def _validate_report(report: object) -> None:
    if not isinstance(report, dict):
        raise DraftPrError("analysis report must be a JSON object")
    required = {
        "diagnosis",
        "evidence",
        "issue",
        "plan",
        "proposed_tests",
        "repo_snapshot_after",
        "repo_snapshot_before",
        "repository_unchanged",
        "risks",
        "status",
    }
    if not required.issubset(report):
        raise DraftPrError("analysis report is missing required fields")
    if report["status"] != "ready_for_human_review":
        raise DraftPrError("only review-ready analysis can produce a Draft PR")
    issue = report["issue"]
    if not isinstance(issue, dict) or not isinstance(issue.get("title"), str):
        raise DraftPrError("analysis issue is invalid")
    for field in ("diagnosis", "repo_snapshot_before", "repo_snapshot_after"):
        if not isinstance(report[field], str) or not report[field]:
            raise DraftPrError(f"analysis {field} is invalid")
    if (
        report["repository_unchanged"] is not True
        or report["repo_snapshot_before"] != report["repo_snapshot_after"]
    ):
        raise DraftPrError("analysis report does not prove an unchanged repository")
    for field in ("evidence", "plan", "proposed_tests", "risks"):
        if not isinstance(report[field], list):
            raise DraftPrError(f"analysis {field} must be a list")
    if not report["plan"]:
        raise DraftPrError("analysis plan cannot be empty")
    evidence_ids: set[str] = set()
    for item in report["evidence"]:
        if not isinstance(item, dict) or not {
            "end_line",
            "evidence_id",
            "path",
            "reason",
            "start_line",
        }.issubset(item):
            raise DraftPrError("analysis evidence item is invalid")
        evidence_id = item["evidence_id"]
        if not isinstance(evidence_id, str) or not evidence_id:
            raise DraftPrError("analysis evidence ID is invalid")
        if evidence_id in evidence_ids:
            raise DraftPrError("analysis evidence IDs must be unique")
        evidence_ids.add(evidence_id)
    for item in report["plan"]:
        if (
            not isinstance(item, dict)
            or not isinstance(item.get("action"), str)
            or not isinstance(item.get("rationale"), str)
            or not isinstance(item.get("evidence_ids"), list)
            or not item["evidence_ids"]
        ):
            raise DraftPrError("analysis plan item is invalid")
        if (
            any(not isinstance(value, str) for value in item["evidence_ids"])
            or not set(item["evidence_ids"]).issubset(evidence_ids)
        ):
            raise DraftPrError("analysis plan cites unknown evidence")
